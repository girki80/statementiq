// ─── Convert Page (PDF↔Word, Excel→PDF etc) ──────────────────────────────────
const CONVERT_TYPES = [
  { id:"pdf-to-docx",  icon:"📄→📝", label:"PDF to Word",        from:"PDF",  to:"Word (.docx)",  accept:".pdf",  desc:"Convert any PDF into an editable Word document" },
  { id:"docx-to-pdf",  icon:"📝→📄", label:"Word to PDF",        from:"Word", to:"PDF",            accept:".docx,.doc", desc:"Convert Word documents to PDF" },
  { id:"xlsx-to-pdf",  icon:"📊→📄", label:"Excel to PDF",       from:"Excel",to:"PDF",            accept:".xlsx,.xls", desc:"Convert Excel spreadsheets to PDF" },
  { id:"pptx-to-pdf",  icon:"📽→📄", label:"PowerPoint to PDF",  from:"PPT",  to:"PDF",            accept:".pptx", desc:"Convert PowerPoint presentations to PDF" },
];

function ConvertPage() {
  const { apiFetch } = useAuth();
  const nav = useNavigate();
  const [active, setActive] = useState(null);
  const [file, setFile] = useState(null);
  const [status, setStatus] = useState("idle");
  const [error, setError] = useState("");
  const [resultUrl, setResultUrl] = useState(null);
  const [resultName, setResultName] = useState("");
  const inputRef = useRef();
  const conv = CONVERT_TYPES.find(c => c.id === active);

  const reset = () => { setFile(null); setStatus("idle"); setError(""); setResultUrl(null); };

  const run = async () => {
    if (!file || !active) return;
    setStatus("processing"); setError("");
    try {
      const fd = new FormData(); fd.append("file", file);
      const res = await apiFetch(`/api/convert/${active}`, { method:"POST", body:fd });
      if (!res.ok) { const d = await res.json(); throw new Error(d.error); }
      const blob = await res.blob();
      const url = URL.createObjectURL(blob);
      const ext = active.split("-to-")[1];
      setResultUrl(url);
      setResultName(`${file.name.replace(/\.[^.]+$/,"")}.${ext}`);
      setStatus("done");
    } catch(e) { setError(e.message); setStatus("error"); }
  };

  return (
    <div style={{minHeight:"100vh",background:`radial-gradient(ellipse at 15% 0%, #0d2422 0%, ${C.bg} 65%)`,color:C.text,padding:"0 16px 60px"}}>
      <style>{GS}</style>
      <div style={{maxWidth:860,margin:"0 auto",paddingTop:28}}>
        <div style={{marginBottom:28}}>
          <h1 style={{fontFamily:C.serif,fontSize:"clamp(1.8rem,4vw,2.6rem)",fontWeight:700,marginBottom:6}}>Document Converter</h1>
          <p style={{color:C.muted,fontSize:13}}>Convert between PDF, Word, Excel and PowerPoint — powered by CloudConvert.</p>
        </div>

        {/* Conversion type grid */}
        <div style={{display:"grid",gridTemplateColumns:"repeat(auto-fill,minmax(200px,1fr))",gap:12,marginBottom:28}}>
          {CONVERT_TYPES.map(c => (
            <div key={c.id} onClick={()=>{setActive(c.id);reset();}}
              style={{background:active===c.id?C.accent+"22":C.surface,border:`1px solid ${active===c.id?C.accent+"88":C.border}`,
                borderRadius:10,padding:"16px 14px",cursor:"pointer",transition:"all .25s"}}
              onMouseEnter={e=>{if(active!==c.id){e.currentTarget.style.borderColor=C.accent+"44";e.currentTarget.style.transform="translateY(-2px)";}}}
              onMouseLeave={e=>{if(active!==c.id){e.currentTarget.style.borderColor=C.border;e.currentTarget.style.transform="translateY(0)";}}}> 
              <div style={{fontSize:24,marginBottom:8}}>{c.icon}</div>
              <div style={{fontWeight:700,fontSize:13,color:active===c.id?C.accent:C.text,marginBottom:4}}>{c.label}</div>
              <div style={{fontSize:11,color:C.muted,lineHeight:1.5}}>{c.desc}</div>
            </div>
          ))}
        </div>

        {conv && (
          <div style={{background:C.surface,border:`1px solid ${C.accent+"44"}`,borderRadius:12,padding:"28px 24px"}} className="fade-up">
            <div style={{display:"flex",alignItems:"center",gap:10,marginBottom:20}}>
              <span style={{fontSize:24}}>{conv.icon}</span>
              <div>
                <div style={{fontWeight:700,fontSize:15,color:C.accent}}>{conv.label}</div>
                <div style={{fontSize:12,color:C.muted}}>{conv.from} → {conv.to} · 1 credit per conversion</div>
              </div>
            </div>

            {status === "idle" && (
              <>
                <div onClick={()=>inputRef.current?.click()}
                  style={{border:`2px dashed ${file?C.accent:C.border}`,borderRadius:10,padding:"36px 20px",textAlign:"center",cursor:"pointer",background:file?C.accent+"08":C.bg,transition:"all .2s",marginBottom:16}}>
                  {!file ? (
                    <><div style={{fontSize:36,marginBottom:10}}>{conv.icon}</div>
                    <div style={{fontSize:14,fontWeight:600,color:C.mid,marginBottom:4}}>Drop your {conv.from} file here</div>
                    <div style={{fontSize:11,color:C.muted}}>Max 50MB</div></>
                  ) : (
                    <><div style={{fontSize:28,color:C.accent,marginBottom:8}}>✓</div>
                    <div style={{fontSize:13,color:C.text,fontWeight:600}}>{file.name}</div>
                    <div style={{fontSize:11,color:C.muted,marginTop:4}}>{(file.size/1024).toFixed(1)} KB</div>
                    <button onClick={e=>{e.stopPropagation();setFile(null);}} style={{marginTop:8,background:"none",border:"none",color:C.muted,fontSize:11,cursor:"pointer"}}>Remove</button></>
                  )}
                  <input ref={inputRef} type="file" hidden accept={conv.accept} onChange={e=>setFile(e.target.files[0])}/>
                </div>
                {file && <Btn onClick={run}>{conv.icon} Convert to {conv.to}</Btn>}
              </>
            )}

            {status==="processing" && (
              <div style={{textAlign:"center",padding:"40px 0"}}>
                <div style={{fontSize:40,animation:"spin 1.5s linear infinite",display:"inline-block",marginBottom:14}}>⚙️</div>
                <div style={{color:C.accent,fontSize:14,fontWeight:600}}>Converting via CloudConvert…</div>
                <div style={{color:C.muted,fontSize:12,marginTop:6}}>This usually takes 10–30 seconds</div>
              </div>
            )}

            {status==="done" && (
              <div style={{textAlign:"center",padding:"28px 0"}}>
                <div style={{fontSize:40,color:C.accent,marginBottom:12}}>✓</div>
                <div style={{fontFamily:C.serif,fontSize:20,color:C.accent,fontWeight:700,marginBottom:20}}>Conversion complete!</div>
                <div style={{display:"flex",gap:10,justifyContent:"center",flexWrap:"wrap"}}>
                  <Btn onClick={()=>Object.assign(document.createElement("a"),{href:resultUrl,download:resultName}).click()}>⬇ Download {conv.to}</Btn>
                  <Btn v="secondary" onClick={()=>{reset();setActive(null);}}>↺ Convert Another</Btn>
                </div>
              </div>
            )}

            {status==="error" && (
              <div style={{textAlign:"center",padding:"28px 0"}}>
                <div style={{fontSize:36,marginBottom:12}}>⚠️</div>
                <div style={{color:C.red,fontSize:13,marginBottom:16,maxWidth:400,margin:"0 auto 16px"}}>{error}</div>
                <Btn v="secondary" onClick={()=>setStatus("idle")}>Try Again</Btn>
              </div>
            )}
          </div>
        )}
      </div>
    </div>
  );
}

