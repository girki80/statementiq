const dlBlob = (content,name,mime) => { const url=URL.createObjectURL(new Blob([content],{type:mime})); Object.assign(document.createElement("a"),{href:url,download:name}).click(); URL.revokeObjectURL(url); };

function buildXLSX(parsed, maps, sym, firm) {
  const wb = XLSX.utils.book_new();
  const meta = [...(firm?[["Generated by",firm.name],[""," "]]:[]),["Document Type",parsed.document_type],["Title",parsed.title],...Object.entries(parsed.metadata||{})];
  if(parsed.summary) Object.entries(parsed.summary).filter(([,v])=>v).forEach(([k,v])=>meta.push([k.replace(/_/g," "),v]));
  const mws=XLSX.utils.aoa_to_sheet(meta); mws["!cols"]=[{wch:26},{wch:44}];
  XLSX.utils.book_append_sheet(wb,mws,"Info");
  (parsed.sheets||[]).forEach((sheet,si)=>{
    const map=maps[si]||sheet.headers.map((h,i)=>({label:h,index:i,enabled:true}));
    const en=map.filter(c=>c.enabled), cc=detCC(sheet.headers,sheet.rows);
    const ws=XLSX.utils.aoa_to_sheet([en.map(c=>c.label),...sheet.rows.map(row=>en.map(c=>sym&&cc[c.index]?fmtC(row[c.index],sym):row[c.index]??""))]);
    ws["!cols"]=en.map(()=>({wch:22}));
    XLSX.utils.book_append_sheet(wb,ws,sheet.name.slice(0,31));
  });
  return XLSX.write(wb,{bookType:"xlsx",type:"array"});
}

