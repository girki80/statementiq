const isNum = v => { if(!v&&v!==0)return false; const c=String(v).replace(/[₦$€£₵,\s]/g,"").replace(/[()]/g,"-"); return !isNaN(parseFloat(c))&&isFinite(c); };
const fmtC = (v,s) => { if(!s||!isNum(v))return v; const c=String(v).replace(/[₦$€£₵,\s]/g,"").replace(/[()]/g,"-"); const n=parseFloat(c); if(isNaN(n))return v; const f=Math.abs(n).toLocaleString("en-US",{minimumFractionDigits:2,maximumFractionDigits:2}); return n<0?`(${s}${f})`:`${s}${f}`; };
const detCC = (headers,rows) => { const r={}; headers.forEach((h,ci)=>{ if(!/amount|balance|debit|credit|total|fee|charge|price|payment|value|sum/i.test(h))return; if(rows.filter(r=>isNum(r[ci])).length>rows.length*.4)r[ci]=true; }); return r; };
